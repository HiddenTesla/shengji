// 游戏速度档位
// 菜单「选项 → 游戏速度」与 App 的动画延时共用这一份定义。
// ============================================================

/** 档位 1..5 对应的时长倍率（越大 = 越快） */
export const SPEED_MULTIPLIERS = [1.2, 0.7, 0.4, 0.28, 0.16] as const;

/** 可选的速度档位（1..5） */
export const SPEED_LEVELS: readonly number[] =
  SPEED_MULTIPLIERS.map((_, index) => index + 1);
